#include <stdio.h>
#include <stdlib.h>

// ========================================
// 錯誤 A：未初始化指標
// ========================================
void error_a() {
    int *p;
    *p = 42;
    printf("%d\n", *p);
}

// ========================================
// 錯誤 B：Dangling Pointer
// ========================================
int* error_b() {
    int x = 100;
    return &x;
}

// ========================================
// 錯誤 C：指標型態混淆
// ========================================
void error_c() {
    int x = 10;
    int *p = &x;
    
    printf("值是: %d\n", p);    // 忘記 *
    printf("位址是: %d\n", *p); // 錯用 *
}

// ========================================
// 錯誤 D：陣列越界 + 指標
// ========================================
void error_d() {
    int arr[3] = {10, 20, 30};
    int *p = arr;
    
    for (int i = 0; i <= 3; i++) {
        printf("%d ", *(p + i));
    }
}

// ========================================
// 錯誤 E：free 後使用
// ========================================
void error_e() {
    int *p = (int*)malloc(sizeof(int));
    *p = 42;
    free(p);
    printf("%d\n", *p);  // 使用已釋放的記憶體
}

// ========================================
// 錯誤 F：記憶體洩漏
// ========================================
void error_f() {
    for (int i = 0; i < 1000; i++) {
        int *p = (int*)malloc(100 * sizeof(int));
        p[0] = i;
        // 沒有 free
    }
}

int main() {
    printf("請閱讀程式碼，在 error_answers.md 中分析錯誤\n");
    return 0;
}
