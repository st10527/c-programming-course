#include <stdio.h>

int main() {
    // ========================================
    // 題目 1：基本 for 迴圈
    // ========================================
    printf("=== 題目 1 ===\n");
    int sum1 = 0;
    for (int i = 1; i <= 5; i++) {
        sum1 += i;
        printf("i=%d, sum=%d\n", i, sum1);
    }
    printf("最終 sum = %d\n", sum1);
    
    // ========================================
    // 題目 2：步進值不是 1
    // ========================================
    printf("\n=== 題目 2 ===\n");
    for (int i = 0; i < 10; i += 3) {
        printf("%d ", i);
    }
    printf("\n");
    
    // ========================================
    // 題目 3：遞減迴圈
    // ========================================
    printf("\n=== 題目 3 ===\n");
    int product = 1;
    for (int i = 5; i >= 1; i--) {
        product *= i;
    }
    printf("5! = %d\n", product);
    
    // ========================================
    // 題目 4：while 迴圈
    // ========================================
    printf("\n=== 題目 4 ===\n");
    int n = 12345;
    int digits = 0;
    while (n > 0) {
        n /= 10;
        digits++;
    }
    printf("位數 = %d\n", digits);
    
    // ========================================
    // 題目 5：累加與條件
    // ========================================
    printf("\n=== 題目 5 ===\n");
    int total = 0;
    for (int i = 1; i <= 10; i++) {
        if (i % 3 == 0) {
            total += i;
        }
    }
    printf("1-10 中 3 的倍數總和 = %d\n", total);
    
    // ========================================
    // 題目 6：提早結束
    // ========================================
    printf("\n=== 題目 6 ===\n");
    int sum6 = 0;
    for (int i = 1; i <= 100; i++) {
        sum6 += i;
        if (sum6 > 50) {
            printf("在 i=%d 時，sum 首次超過 50\n", i);
            break;
        }
    }
    printf("此時 sum = %d\n", sum6);
    
    return 0;
}
