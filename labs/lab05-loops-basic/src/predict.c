/**
 * Lab 05 Part 3: 預測輸出
 * 
 * 先預測每個迴圈的輸出，再執行驗證。
 */

#include <stdio.h>

int main() {
    // ========================================
    // 題目 A
    // ========================================
    printf("=== 題目 A ===\n");
    for (int i = 0; i < 5; i++) {
        printf("*");
    }
    printf("\n");
    
    // ========================================
    // 題目 B
    // ========================================
    printf("\n=== 題目 B ===\n");
    for (int i = 1; i <= 3; i++) {
        for (int j = 1; j <= 3; j++) {
            printf("%d", i * j);
        }
        printf("\n");
    }
    
    // ========================================
    // 題目 C
    // ========================================
    printf("\n=== 題目 C ===\n");
    int x = 10;
    while (x > 0) {
        printf("%d ", x);
        x -= 3;
    }
    printf("\n");
    
    // ========================================
    // 題目 D
    // ========================================
    printf("\n=== 題目 D ===\n");
    for (int i = 1; i <= 5; i++) {
        if (i == 3) continue;
        printf("%d ", i);
    }
    printf("\n");
    
    // ========================================
    // 題目 E
    // ========================================
    printf("\n=== 題目 E ===\n");
    for (int i = 1; i <= 5; i++) {
        if (i == 3) break;
        printf("%d ", i);
    }
    printf("\n");
    
    // ========================================
    // 題目 F：迴圈不執行
    // ========================================
    printf("\n=== 題目 F ===\n");
    for (int i = 10; i < 5; i++) {
        printf("Hello\n");
    }
    printf("Done\n");
    
    // ========================================
    // 題目 G：do-while 至少執行一次
    // ========================================
    printf("\n=== 題目 G ===\n");
    int y = 10;
    do {
        printf("y = %d\n", y);
        y++;
    } while (y < 5);
    
    return 0;
}
