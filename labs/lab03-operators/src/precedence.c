#include <stdio.h>

int main() {
    printf("=== 運算子優先順序練習 ===\n\n");
    
    // ========================================
    // 題目 1：基本優先順序
    // ========================================
    int result1 = 2 + 3 * 4;
    printf("題目 1: 2 + 3 * 4 = %d\n", result1);
    
    // ========================================
    // 題目 2：括號改變順序
    // ========================================
    int result2 = (2 + 3) * 4;
    printf("題目 2: (2 + 3) * 4 = %d\n", result2);
    
    // ========================================
    // 題目 3：混合運算
    // ========================================
    int result3 = 10 - 4 / 2 + 1;
    printf("題目 3: 10 - 4 / 2 + 1 = %d\n", result3);
    
    // ========================================
    // 題目 4：餘數運算
    // ========================================
    int result4 = 17 % 5 + 3 * 2;
    printf("題目 4: 17 %% 5 + 3 * 2 = %d\n", result4);
    
    // ========================================
    // 題目 5：複雜表達式
    // ========================================
    int result5 = 2 + 3 * 4 - 6 / 2;
    printf("題目 5: 2 + 3 * 4 - 6 / 2 = %d\n", result5);
    
    // ========================================
    // 題目 6：連續賦值
    // ========================================
    int a, b, c;
    a = b = c = 5;
    a = a + b + c;
    printf("題目 6: a = %d\n", a);
    
    // ========================================
    // 題目 7：遞增與運算
    // ========================================
    int x = 3;
    int result7 = x++ + ++x;
    printf("題目 7: x++ + ++x = %d (x = %d)\n", result7, x);
    // 注意：這種寫法在實際程式中應該避免！
    
    // ========================================
    // 題目 8：比較與賦值（陷阱題）
    // ========================================
    int y = 5;
    int result8 = (y = 10);  // 這是賦值，不是比較！
    printf("題目 8: (y = 10) 的值是 %d\n", result8);
    
    return 0;
}
