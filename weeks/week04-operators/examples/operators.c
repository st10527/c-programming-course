/**
 * operators.c - 運算子完整示範
 * 
 * 這個程式示範 C 語言中各種運算子的使用。
 * 
 * 編譯：gcc operators.c -o operators
 * 執行：./operators
 */

#include <stdio.h>

int main() {
    // ============================================================
    // 算術運算子 (Arithmetic Operators)
    // ============================================================
    
    printf("=== 算術運算子 ===\n");
    
    int a = 17, b = 5;
    printf("a = %d, b = %d\n", a, b);
    printf("a + b = %d\n", a + b);   // 加法：22
    printf("a - b = %d\n", a - b);   // 減法：12
    printf("a * b = %d\n", a * b);   // 乘法：85
    printf("a / b = %d\n", a / b);   // 整數除法：3（不是 3.4！）
    printf("a %% b = %d\n", a % b);  // 餘數：2
    printf("\n");
    
    // ============================================================
    // 整數除法 vs 浮點數除法
    // ============================================================
    
    printf("=== 整數除法 vs 浮點數除法 ===\n");
    
    int x = 7, y = 2;
    
    // 兩個 int 相除 → 整數除法
    int result1 = x / y;
    printf("(int) 7 / 2 = %d\n", result1);       // 3
    
    // 即使存入 double，結果還是整數除法
    double result2 = x / y;
    printf("(double) 7 / 2 = %f\n", result2);     // 3.000000
    
    // 用型態轉換得到正確結果
    double result3 = (double)x / y;
    printf("(double)7 / 2 = %f\n", result3);      // 3.500000
    
    // 其中一個是浮點數就會自動轉換
    double result4 = x / 2.0;
    printf("7 / 2.0 = %f\n", result4);            // 3.500000
    printf("\n");
    
    // ============================================================
    // 指派運算子 (Assignment Operators)
    // ============================================================
    
    printf("=== 指派運算子 ===\n");
    
    int n = 10;
    printf("初始值: n = %d\n", n);
    
    n += 5;    // n = n + 5
    printf("n += 5:  n = %d\n", n);    // 15
    
    n -= 3;    // n = n - 3
    printf("n -= 3:  n = %d\n", n);    // 12
    
    n *= 2;    // n = n * 2
    printf("n *= 2:  n = %d\n", n);    // 24
    
    n /= 4;   // n = n / 4
    printf("n /= 4:  n = %d\n", n);   // 6
    
    n %= 4;   // n = n % 4
    printf("n %%= 4:  n = %d\n", n);  // 2
    printf("\n");
    
    // ============================================================
    // 遞增遞減運算子 (Increment/Decrement)
    // ============================================================
    
    printf("=== 遞增遞減運算子 ===\n");
    
    int p = 5;
    int q = 5;
    
    // 後置 (postfix)：先使用，再加 1
    int result_post = p++;
    printf("後置 p++: result = %d, p = %d\n", result_post, p);  // 5, 6
    
    // 前置 (prefix)：先加 1，再使用
    int result_pre = ++q;
    printf("前置 ++q: result = %d, q = %d\n", result_pre, q);   // 6, 6
    printf("\n");
    
    // ============================================================
    // 運算子優先順序
    // ============================================================
    
    printf("=== 運算子優先順序 ===\n");
    
    // 乘除優先於加減
    printf("2 + 3 * 4 = %d\n", 2 + 3 * 4);         // 14
    printf("(2 + 3) * 4 = %d\n", (2 + 3) * 4);     // 20
    
    // 混合運算
    printf("10 - 4 / 2 + 1 = %d\n", 10 - 4 / 2 + 1);   // 9
    printf("17 %% 5 + 3 * 2 = %d\n", 17 % 5 + 3 * 2);   // 8
    
    // 建議：有疑慮時加括號
    printf("2 + (3 * 4) - (6 / 2) = %d\n", 2 + (3 * 4) - (6 / 2)); // 11
    printf("\n");
    
    // ============================================================
    // 優先順序參考表（由高到低）
    // ============================================================
    /*
     * 1. () 括號
     * 2. ++ -- (前置)、(type) 型態轉換
     * 3. * / % 乘除餘
     * 4. + - 加減
     * 5. < <= > >= 比較
     * 6. == != 相等
     * 7. && 邏輯 AND
     * 8. || 邏輯 OR
     * 9. = += -= *= /= %= 指派
     * 
     * 建議：不確定時就加括號！
     */
    
    return 0;
}
