/**
 * mistakes.c - 常見迴圈錯誤示範
 * 
 * 這個程式展示常見的迴圈錯誤和正確寫法。
 * 
 * 編譯：gcc mistakes.c -o mistakes
 * 執行：./mistakes
 */

#include <stdio.h>

int main() {
    // ============================================================
    // 錯誤 1：分號放錯位置
    // ============================================================
    
    printf("=== 錯誤 1：多餘的分號 ===\n");
    
    // ❌ for 後面多了分號，{} 只執行一次
    printf("錯誤版本: ");
    int i;
    for (i = 0; i < 5; i++);  // ← 這個分號讓迴圈主體是空的
    {
        printf("* ");  // 只印一次
    }
    printf("\n");
    
    // ✅ 正確版本
    printf("正確版本: ");
    for (int i = 0; i < 5; i++) {
        printf("* ");
    }
    printf("\n\n");
    
    // ============================================================
    // 錯誤 2：Off-by-one
    // ============================================================
    
    printf("=== 錯誤 2：Off-by-one ===\n");
    
    // 目標：印 5 個數字 (1-5)
    printf("< 5 (從1開始): ");
    for (int i = 1; i < 5; i++) {  // 只印 1,2,3,4 → 少一個！
        printf("%d ", i);
    }
    printf(" → 只有 4 個！\n");
    
    printf("<= 5 (從1開始): ");
    for (int i = 1; i <= 5; i++) {  // 正確：1,2,3,4,5
        printf("%d ", i);
    }
    printf(" → 5 個 ✓\n");
    
    printf("< 5 (從0開始): ");
    for (int i = 0; i < 5; i++) {   // 也是 5 次：0,1,2,3,4
        printf("%d ", i);
    }
    printf(" → 5 個 ✓\n\n");
    
    // ============================================================
    // 錯誤 3：if 後面多了分號
    // ============================================================
    
    printf("=== 錯誤 3：if 後面的分號 ===\n");
    
    // ❌ 印出偶數（錯誤版）
    printf("錯誤: ");
    for (int i = 1; i <= 10; i++) {
        if (i % 2 == 0);  // ← 分號讓 if 失效
        {
            printf("%d ", i);  // 全部都印了
        }
    }
    printf("\n");
    
    // ✅ 正確版
    printf("正確: ");
    for (int i = 1; i <= 10; i++) {
        if (i % 2 == 0) {
            printf("%d ", i);
        }
    }
    printf("\n\n");
    
    // ============================================================
    // 錯誤 4：遞減迴圈方向錯誤
    // ============================================================
    
    printf("=== 錯誤 4：遞減方向 ===\n");
    
    // ❌ 想從 5 印到 1，但 i++ 讓 i 越來越大 → 永遠不會結束
    // for (int i = 5; i >= 1; i++) ← 無窮迴圈！
    printf("錯誤: for (i=5; i>=1; i++) → 無窮迴圈！\n");
    
    // ✅ 正確
    printf("正確: ");
    for (int i = 5; i >= 1; i--) {
        printf("%d ", i);
    }
    printf("\n\n");
    
    // ============================================================
    // 錯誤 5：階乘初始值
    // ============================================================
    
    printf("=== 錯誤 5：初始值設錯 ===\n");
    
    // ❌ 初始值設為 0，乘法結果永遠是 0
    int fact_wrong = 0;
    for (int i = 1; i <= 5; i++) {
        fact_wrong *= i;
    }
    printf("初始值 0: 5! = %d (永遠是 0！)\n", fact_wrong);
    
    // ✅ 乘法的初始值應該是 1
    int fact_right = 1;
    for (int i = 1; i <= 5; i++) {
        fact_right *= i;
    }
    printf("初始值 1: 5! = %d ✓\n", fact_right);
    
    return 0;
}

