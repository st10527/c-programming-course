/**
 * nested.c - 巢狀迴圈示範
 * 
 * 編譯：gcc nested.c -o nested
 * 執行：./nested
 */

#include <stdio.h>

int main() {
    // ============================================================
    // 巢狀迴圈基本概念
    // ============================================================
    
    printf("=== 巢狀迴圈執行順序 ===\n");
    
    for (int i = 1; i <= 3; i++) {
        for (int j = 1; j <= 4; j++) {
            printf("(%d,%d) ", i, j);
        }
        printf("\n");
    }
    printf("內層共執行 3 × 4 = 12 次\n\n");
    
    // ============================================================
    // 九九乘法表
    // ============================================================
    
    printf("=== 九九乘法表 ===\n");
    
    for (int i = 1; i <= 9; i++) {
        for (int j = 1; j <= 9; j++) {
            printf("%2d ", i * j);  // %2d 讓數字對齊
        }
        printf("\n");
    }
    printf("\n");
    
    // ============================================================
    // 三角形圖案
    // ============================================================
    
    printf("=== 直角三角形 ===\n");
    
    int n = 5;
    for (int i = 1; i <= n; i++) {
        for (int j = 1; j <= i; j++) {
            printf("* ");
        }
        printf("\n");
    }
    printf("\n");
    
    // ============================================================
    // 數字三角形
    // ============================================================
    
    printf("=== 數字三角形 ===\n");
    
    for (int i = 1; i <= 5; i++) {
        for (int j = 1; j <= i; j++) {
            printf("%d ", j);
        }
        printf("\n");
    }
    printf("\n");
    
    // ============================================================
    // 等腰三角形
    // ============================================================
    
    printf("=== 等腰三角形 ===\n");
    
    for (int i = 1; i <= n; i++) {
        // 先印空格
        for (int j = 1; j <= n - i; j++) {
            printf(" ");
        }
        // 再印星號
        for (int j = 1; j <= 2 * i - 1; j++) {
            printf("*");
        }
        printf("\n");
    }
    printf("\n");
    
    // ============================================================
    // break 和 continue
    // ============================================================
    
    printf("=== break ===\n");
    printf("找第一個能被 7 整除的數: ");
    for (int i = 1; i <= 100; i++) {
        if (i % 7 == 0) {
            printf("%d\n", i);
            break;  // 找到就停
        }
    }
    
    printf("\n=== continue ===\n");
    printf("1-10 中不是 3 的倍數: ");
    for (int i = 1; i <= 10; i++) {
        if (i % 3 == 0) {
            continue;  // 跳過 3 的倍數
        }
        printf("%d ", i);
    }
    printf("\n\n");
    
    // ============================================================
    // break 在巢狀迴圈中只跳出一層
    // ============================================================
    
    printf("=== break 在巢狀迴圈中 ===\n");
    
    for (int i = 1; i <= 3; i++) {
        printf("外層 i=%d: ", i);
        for (int j = 1; j <= 5; j++) {
            if (j == 3) break;  // 只跳出內層
            printf("j=%d ", j);
        }
        printf("(內層被 break)\n");
    }
    // 外層還是會執行 3 次！
    
    return 0;
}
