/**
 * variables.c - 變數與資料型態示範
 * 
 * 這個程式示範 C 語言中各種基本資料型態的使用。
 */

#include <stdio.h>

int main() {
    // ============================================================
    // 整數型態 (Integer Types)
    // ============================================================
    
    int age = 20;                // 最常用的整數型態
    short small = 100;           // 較小範圍的整數
    long big = 1234567890L;      // 較大範圍的整數
    
    printf("=== 整數型態 ===\n");
    printf("int age = %d\n", age);
    printf("short small = %d\n", small);
    printf("long big = %ld\n", big);
    printf("\n");
    
    // ============================================================
    // 浮點數型態 (Floating-Point Types)
    // ============================================================
    
    float price = 19.99f;        // 單精度浮點數
    double pi = 3.14159265359;   // 雙精度浮點數（推薦）
    
    printf("=== 浮點數型態 ===\n");
    printf("float price = %f\n", price);
    printf("double pi = %.10f\n", pi);  // 顯示 10 位小數
    printf("\n");
    
    // ============================================================
    // 字元型態 (Character Type)
    // ============================================================
    
    char grade = 'A';            // 單一字元，用單引號
    char newline = '\n';         // 特殊字元
    
    printf("=== 字元型態 ===\n");
    printf("char grade = %c\n", grade);
    printf("grade 的 ASCII 值 = %d\n", grade);  // 字元其實是數字
    printf("\n");
    
    // ============================================================
    // 常數 (Constants)
    // ============================================================
    
    const int MAX_SCORE = 100;   // 常數不能被修改
    const double TAX_RATE = 0.05;
    
    printf("=== 常數 ===\n");
    printf("MAX_SCORE = %d\n", MAX_SCORE);
    printf("TAX_RATE = %.2f\n", TAX_RATE);
    printf("\n");
    
    // MAX_SCORE = 200;  // 這行會編譯錯誤！常數不能修改
    
    // ============================================================
    // 變數宣告與初始化
    // ============================================================
    
    printf("=== 宣告與初始化 ===\n");
    
    // 方式 1：宣告後再賦值
    int x;
    x = 10;
    
    // 方式 2：宣告同時初始化（推薦）
    int y = 20;
    
    // 方式 3：一次宣告多個變數
    int a = 1, b = 2, c = 3;
    
    printf("x = %d, y = %d\n", x, y);
    printf("a = %d, b = %d, c = %d\n", a, b, c);
    
    return 0;
}
