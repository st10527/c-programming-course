/**
 * memory.c - 記憶體概念示範
 * 
 * 這個程式示範變數在記憶體中的儲存方式。
 */

#include <stdio.h>

int main() {
    // ============================================================
    // 變數的記憶體位址
    // ============================================================
    
    int number = 42;
    
    printf("=== 記憶體位址 ===\n");
    printf("變數名稱: number\n");
    printf("儲存的值: %d\n", number);
    printf("記憶體位址: %p\n", (void*)&number);  // & 取得位址
    printf("\n");
    
    // ============================================================
    // sizeof 運算子
    // ============================================================
    
    printf("=== 各型態所佔空間 ===\n");
    printf("char:   %lu bytes\n", sizeof(char));
    printf("short:  %lu bytes\n", sizeof(short));
    printf("int:    %lu bytes\n", sizeof(int));
    printf("long:   %lu bytes\n", sizeof(long));
    printf("float:  %lu bytes\n", sizeof(float));
    printf("double: %lu bytes\n", sizeof(double));
    printf("\n");
    
    // ============================================================
    // 多個變數的記憶體配置
    // ============================================================
    
    int a = 10;
    int b = 20;
    int c = 30;
    
    printf("=== 多個變數的位址 ===\n");
    printf("a: 值=%d, 位址=%p\n", a, (void*)&a);
    printf("b: 值=%d, 位址=%p\n", b, (void*)&b);
    printf("c: 值=%d, 位址=%p\n", c, (void*)&c);
    printf("\n");
    
    // 注意：相鄰變數的位址通常相差 sizeof(int) = 4 bytes
    // 但這不是保證的，編譯器可能會調整
    
    // ============================================================
    // 手動追蹤練習
    // ============================================================
    
    printf("=== 手動追蹤練習 ===\n");
    printf("請先在紙上追蹤，再看答案：\n\n");
    
    int x = 5;
    int y = 10;
    printf("初始: x = %d, y = %d\n", x, y);
    
    x = y;      // x 變成 10
    printf("x = y 後: x = %d, y = %d\n", x, y);
    
    y = 20;     // y 變成 20，但 x 不受影響
    printf("y = 20 後: x = %d, y = %d\n", x, y);
    
    x = x + 1;  // x 變成 11
    printf("x = x + 1 後: x = %d, y = %d\n", x, y);
    
    printf("\n");
    
    // ============================================================
    // 未初始化的危險
    // ============================================================
    
    printf("=== 未初始化變數 ===\n");
    
    int uninitialized;  // 沒有給初始值
    
    // 警告：這個值是「垃圾值」，每次執行可能不同
    // 這是一個常見的 bug 來源！
    printf("未初始化的變數: %d (這是垃圾值！)\n", uninitialized);
    printf("永遠要初始化你的變數！\n");
    
    return 0;
}

/*
 * 記憶體圖示說明：
 * 
 * 假設 int 佔 4 bytes，記憶體可以想像成這樣：
 * 
 * 位址        內容
 * --------   ------
 * 0x1000     [  a = 10  ]  (4 bytes)
 * 0x1004     [  b = 20  ]  (4 bytes)
 * 0x1008     [  c = 30  ]  (4 bytes)
 * 
 * 每個變數有：
 * 1. 名稱 (給程式設計師用)
 * 2. 位址 (記憶體中的位置)
 * 3. 值   (儲存的資料)
 * 4. 型態 (決定如何解讀資料)
 */
