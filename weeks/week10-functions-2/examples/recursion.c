#include <stdio.h>

// ============================================================
// 函式宣告
// ============================================================

int factorial(int n);
int factorial_iter(int n);
int fib(int n);
int sum_digits(int n);
int power(int base, int exp);

// ============================================================
// 主程式
// ============================================================

int main() {
    // --------------------------------------------------------
    // 範例 1：階乘
    // --------------------------------------------------------
    
    printf("=== 階乘 ===\n");
    
    for (int i = 0; i <= 6; i++) {
        printf("%d! = %d (遞迴) = %d (迭代)\n",
               i, factorial(i), factorial_iter(i));
    }
    printf("\n");
    
    // --------------------------------------------------------
    // 範例 2：費波那契數列
    // --------------------------------------------------------
    
    printf("=== 費波那契數列 ===\n");
    printf("fib: ");
    for (int i = 0; i <= 10; i++) {
        printf("%d ", fib(i));
    }
    printf("\n\n");
    
    // --------------------------------------------------------
    // 範例 3：位數和
    // --------------------------------------------------------
    
    printf("=== 位數和 ===\n");
    printf("sum_digits(1234) = %d\n", sum_digits(1234));  // 1+2+3+4 = 10
    printf("sum_digits(999) = %d\n", sum_digits(999));    // 9+9+9 = 27
    printf("\n");
    
    // --------------------------------------------------------
    // 範例 4：次方
    // --------------------------------------------------------
    
    printf("=== 次方 ===\n");
    printf("2^10 = %d\n", power(2, 10));  // 1024
    printf("3^4 = %d\n", power(3, 4));    // 81
    printf("\n");
    
    // --------------------------------------------------------
    // 遞迴 vs 迭代的比較
    // --------------------------------------------------------
    
    printf("=== 遞迴 vs 迭代 ===\n");
    printf("遞迴：程式碼簡潔，但有函式呼叫開銷\n");
    printf("迭代：效率較高，但有時程式碼較複雜\n");
    printf("建議：先寫出正確的程式，再考慮效率\n");
    
    return 0;
}

// ============================================================
// 函式定義
// ============================================================

/**
 * 階乘（遞迴版）
 * n! = n × (n-1)!
 * 0! = 1
 */
int factorial(int n) {
    // 基礎情況
    if (n <= 1) {
        return 1;
    }
    // 遞迴情況
    return n * factorial(n - 1);
}

/**
 * 階乘（迭代版）
 */
int factorial_iter(int n) {
    int result = 1;
    for (int i = 2; i <= n; i++) {
        result *= i;
    }
    return result;
}

/**
 * 費波那契數列（遞迴版）
 * fib(0) = 0, fib(1) = 1
 * fib(n) = fib(n-1) + fib(n-2)
 */
int fib(int n) {
    if (n <= 0) return 0;   // 基礎情況
    if (n == 1) return 1;   // 基礎情況
    return fib(n - 1) + fib(n - 2);  // 遞迴情況
}

/**
 * 計算各位數字之和
 * sum_digits(1234) = 4 + sum_digits(123) = 4 + 3 + 2 + 1 = 10
 */
int sum_digits(int n) {
    if (n < 10) return n;            // 基礎情況：個位數
    return n % 10 + sum_digits(n / 10);  // 最後一位 + 其餘位數的和
}

/**
 * 計算 base 的 exp 次方
 * power(2, 3) = 2 * power(2, 2) = 2 * 2 * power(2, 1) = 2 * 2 * 2 = 8
 */
int power(int base, int exp) {
    if (exp == 0) return 1;          // 基礎情況：x^0 = 1
    return base * power(base, exp - 1);  // 遞迴情況
}
