/**
 * functions.c - 函式基礎示範
 * 
 * 這個程式示範 C 語言中函式的定義、呼叫、參數傳遞。
 * 
 * 編譯：gcc functions.c -o functions
 * 執行：./functions
 */

#include <stdio.h>

// ============================================================
// 函式原型（宣告）- 告訴編譯器函式的存在
// ============================================================

int add(int a, int b);
int max_of_three(int a, int b, int c);
void print_line(int length);
void greet(void);
int factorial(int n);

// ============================================================
// 主程式
// ============================================================

int main() {
    // --------------------------------------------------------
    // 基本函式呼叫
    // --------------------------------------------------------
    
    printf("=== 基本函式呼叫 ===\n");
    
    int result = add(3, 5);
    printf("add(3, 5) = %d\n", result);
    
    // 也可以直接在 printf 中呼叫
    printf("add(10, 20) = %d\n", add(10, 20));
    printf("\n");
    
    // --------------------------------------------------------
    // 多參數函式
    // --------------------------------------------------------
    
    printf("=== 多參數函式 ===\n");
    
    printf("max(15, 42, 28) = %d\n", max_of_three(15, 42, 28));
    printf("max(7, 3, 9) = %d\n", max_of_three(7, 3, 9));
    printf("\n");
    
    // --------------------------------------------------------
    // void 函式
    // --------------------------------------------------------
    
    printf("=== void 函式（不回傳值） ===\n");
    
    greet();
    print_line(20);
    printf("上面是一條 20 字元的分隔線\n\n");
    
    // --------------------------------------------------------
    // 函式結果作為另一個函式的參數
    // --------------------------------------------------------
    
    printf("=== 函式組合 ===\n");
    
    int a = 5, b = 3;
    int sum = add(a, b);
    printf("%d! = %d\n", sum, factorial(sum));
    printf("\n");
    
    // --------------------------------------------------------
    // 傳值呼叫示範
    // --------------------------------------------------------
    
    printf("=== 傳值呼叫 ===\n");
    
    int x = 10;
    printf("呼叫前: x = %d\n", x);
    
    // add 函式不會改變 x 的值
    int y = add(x, 5);
    printf("add(x, 5) 後: x = %d, y = %d\n", x, y);
    printf("x 沒有被改變！因為傳的是「值的複製品」\n");
    
    return 0;
}

// ============================================================
// 函式定義（實作）
// ============================================================

/**
 * 計算兩個整數的和
 * @param a 第一個整數
 * @param b 第二個整數
 * @return 兩數之和
 */
int add(int a, int b) {
    return a + b;
}

/**
 * 找出三個整數中的最大值
 */
int max_of_three(int a, int b, int c) {
    int max = a;
    if (b > max) max = b;
    if (c > max) max = c;
    return max;
}

/**
 * 印出一條分隔線
 * @param length 分隔線長度
 */
void print_line(int length) {
    for (int i = 0; i < length; i++) {
        printf("-");
    }
    printf("\n");
}

/**
 * 印出問候語（無參數、無回傳值）
 */
void greet(void) {
    printf("Hello! Welcome to C functions!\n");
}

/**
 * 計算 n 的階乘 (n!)
 * @param n 非負整數
 * @return n!
 */
int factorial(int n) {
    int result = 1;
    for (int i = 2; i <= n; i++) {
        result *= i;
    }
    return result;
}
