/**
 * tracing.c - 迴圈手動追蹤練習
 * 
 * 這個程式用來練習追蹤迴圈的執行過程。
 * 請先在紙上追蹤，再執行程式驗證。
 * 
 * 編譯：gcc tracing.c -o tracing
 * 執行：./tracing
 */

#include <stdio.h>

int main() {
    // ============================================================
    // 範例 1：基本追蹤（帶著做）
    // ============================================================
    
    printf("=== 範例 1：基本追蹤 ===\n");
    
    /*
     * 追蹤表格：
     * 
     * | i | i<=4 | sum  | 說明        |
     * |---|------|------|-------------|
     * | 1 | true | 0→1  | sum = 0+1   |
     * | 2 | true | 1→3  | sum = 1+2   |
     * | 3 | true | 3→6  | sum = 3+3   |
     * | 4 | true | 6→10 | sum = 6+4   |
     * | 5 | false| 10   | 離開迴圈    |
     */
    
    int sum = 0;
    for (int i = 1; i <= 4; i++) {
        sum += i;
        printf("i=%d, sum=%d\n", i, sum);
    }
    printf("最終: sum = %d\n", sum);
    printf("\n");
    
    // ============================================================
    // 範例 2：while 追蹤
    // ============================================================
    
    printf("=== 範例 2：while 追蹤 ===\n");
    
    /*
     * 追蹤表格：
     * 
     * | n     | n>0  | n/10  | digits |
     * |-------|------|-------|--------|
     * | 1234  | true | 123   | 1      |
     * | 123   | true | 12    | 2      |
     * | 12    | true | 1     | 3      |
     * | 1     | true | 0     | 4      |
     * | 0     | false| -     | 4      |
     */
    
    int n = 1234;
    int digits = 0;
    printf("追蹤 n = %d 的位數:\n", n);
    while (n > 0) {
        n /= 10;
        digits++;
        printf("n=%d, digits=%d\n", n, digits);
    }
    printf("位數 = %d\n", digits);
    printf("\n");
    
    // ============================================================
    // 範例 3：邊界條件比較
    // ============================================================
    
    printf("=== 範例 3：< vs <= 的差異 ===\n");
    
    printf("for (i=1; i<5; i++):  ");
    for (int i = 1; i < 5; i++) {
        printf("%d ", i);
    }
    printf(" → 4 次\n");
    
    printf("for (i=1; i<=5; i++): ");
    for (int i = 1; i <= 5; i++) {
        printf("%d ", i);
    }
    printf(" → 5 次\n");
    
    printf("for (i=0; i<5; i++):  ");
    for (int i = 0; i < 5; i++) {
        printf("%d ", i);
    }
    printf(" → 5 次 (從 0 開始)\n");
    printf("\n");
    
    // ============================================================
    // 範例 4：常見錯誤 - Off-by-one
    // ============================================================
    
    printf("=== 範例 4：Off-by-one 錯誤 ===\n");
    
    // 要印 5 個星號
    printf("正確 (i<5):  ");
    for (int i = 0; i < 5; i++) {
        printf("*");
    }
    printf(" → 5 個\n");
    
    printf("錯誤 (i<=5): ");
    for (int i = 0; i <= 5; i++) {
        printf("*");
    }
    printf(" → 6 個！\n");
    
    printf("錯誤 (i<4):  ");
    for (int i = 0; i < 4; i++) {
        printf("*");
    }
    printf(" → 只有 4 個！\n");
    
    return 0;
}
