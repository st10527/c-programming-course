#include <stdio.h>

int main() {
    printf("=== 題目 1：基本巢狀迴圈 ===\n");
    {
        for (int i = 1; i <= 3; i++) {
            for (int j = 1; j <= 3; j++) {
                printf("%d ", i * j);
            }
            printf("\n");
        }
    }
    
    printf("\n=== 題目 2：三角形 ===\n");
    {
        for (int i = 1; i <= 4; i++) {
            for (int j = 1; j <= i; j++) {
                printf("* ");
            }
            printf("\n");
        }
    }
    
    printf("\n=== 題目 3：計數器 ===\n");
    {
        int count = 0;
        for (int i = 0; i < 4; i++) {
            for (int j = 0; j < 3; j++) {
                count++;
            }
        }
        printf("count = %d\n", count);
    }
    
    printf("\n=== 題目 4：break 只跳出一層 ===\n");
    {
        for (int i = 1; i <= 3; i++) {
            for (int j = 1; j <= 3; j++) {
                if (j == 2) break;
                printf("(%d,%d) ", i, j);
            }
            printf("\n");
        }
    }
    
    printf("\n=== 題目 5：累加 ===\n");
    {
        int sum = 0;
        for (int i = 1; i <= 3; i++) {
            for (int j = i; j <= 3; j++) {
                sum += i * j;
            }
        }
        printf("sum = %d\n", sum);
    }
    
    printf("\n=== 題目 6：倒三角 ===\n");
    {
        for (int i = 5; i >= 1; i--) {
            for (int j = 0; j < i; j++) {
                printf("%d ", i);
            }
            printf("\n");
        }
    }
    
    printf("\n=== 題目 7：數字方陣 ===\n");
    {
        int n = 1;
        for (int i = 0; i < 3; i++) {
            for (int j = 0; j < 4; j++) {
                printf("%2d ", n);
                n++;
            }
            printf("\n");
        }
    }
    
    return 0;
}

