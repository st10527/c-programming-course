/**
 * 程式追蹤練習 08：陣列追蹤
 * 難度：⭐⭐
 * 
 * 練習方式：
 * 1. 畫出陣列的內容表格
 * 2. 追蹤每次操作後陣列的變化
 * 3. 注意陣列索引從 0 開始
 * 4. 預測輸出，再執行驗證
 */

#include <stdio.h>

void modify(int arr[], int size) {
    for (int i = 0; i < size; i++) {
        arr[i] = arr[i] * 2;
    }
}

int main() {
    printf("=== 題目 1：陣列初始化 ===\n");
    {
        int a[5] = {10, 20, 30};
        for (int i = 0; i < 5; i++) {
            printf("%d ", a[i]);
        }
        printf("\n");
    }
    
    printf("\n=== 題目 2：陣列修改 ===\n");
    {
        int arr[4] = {1, 2, 3, 4};
        arr[0] = arr[3];
        arr[2] = arr[0] + arr[1];
        printf("%d %d %d %d\n", arr[0], arr[1], arr[2], arr[3]);
    }
    
    printf("\n=== 題目 3：迴圈累加 ===\n");
    {
        int arr[5] = {3, 1, 4, 1, 5};
        int sum = 0;
        for (int i = 0; i < 5; i++) {
            sum += arr[i];
        }
        printf("sum = %d\n", sum);
    }
    
    printf("\n=== 題目 4：反轉 ===\n");
    {
        int arr[5] = {1, 2, 3, 4, 5};
        int n = 5;
        for (int i = 0; i < n / 2; i++) {
            int temp = arr[i];
            arr[i] = arr[n - 1 - i];
            arr[n - 1 - i] = temp;
        }
        for (int i = 0; i < 5; i++) {
            printf("%d ", arr[i]);
        }
        printf("\n");
    }
    
    printf("\n=== 題目 5：函式修改陣列 ===\n");
    {
        int data[3] = {10, 20, 30};
        printf("修改前: %d %d %d\n", data[0], data[1], data[2]);
        modify(data, 3);
        printf("修改後: %d %d %d\n", data[0], data[1], data[2]);
    }
    
    printf("\n=== 題目 6：二維陣列 ===\n");
    {
        int m[2][3] = {{1, 2, 3}, {4, 5, 6}};
        int sum = 0;
        for (int i = 0; i < 2; i++) {
            for (int j = 0; j < 3; j++) {
                sum += m[i][j];
            }
        }
        printf("sum = %d\n", sum);
        printf("m[1][2] = %d\n", m[1][2]);
    }
    
    printf("\n=== 題目 7：Bubble Sort 一輪 ===\n");
    {
        int arr[5] = {5, 3, 8, 1, 9};
        // 執行一輪 bubble sort
        for (int j = 0; j < 4; j++) {
            if (arr[j] > arr[j + 1]) {
                int temp = arr[j];
                arr[j] = arr[j + 1];
                arr[j + 1] = temp;
            }
        }
        for (int i = 0; i < 5; i++) {
            printf("%d ", arr[i]);
        }
        printf("\n");
    }
    
    return 0;
}

